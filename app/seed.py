# (users_min, users_max) — диапазон, в котором действует цена за 1 узел/пользователя
SEAT_TIERS = [(10, 14), (15, 19), (20, 24), (25, 49), (50, 99), (100, 149), (150, 249)]
TIER_FACTOR = [1.0, 0.97, 0.94, 0.9, 0.85, 0.81, 0.77]


def _seat_family(base: dict[str, Any], code: str, price_new_1y: float, terms=(12, 24), renewal=True,
                 tiers=SEAT_TIERS, editions: dict[str, tuple[str, float]] | None = None) -> list[dict[str, Any]]:
    """Сетка «цена за узел/пользователя»: редакция × тип покупки × срок × диапазон."""
    out = []
    editions = editions or {"": ("", 1.0)}
    for ed_code, (ed_name, ed_factor) in editions.items():
        for ptype in (["new", "renewal"] if renewal else ["new"]):
            for term in terms:
                for (lo, hi), f in zip(tiers, TIER_FACTOR):
                    price = price_new_1y * ed_factor * f * (term / 12) * (0.92 if term == 24 else 1.0)
                    price *= 0.6 if ptype == "renewal" else 1.0
                    name_ed = f" {ed_name}" if ed_name else ""
                    out.append({
                        **base,
                        "sku": f"{code}{('-' + ed_code) if ed_code else ''}-{'R' if ptype == 'renewal' else 'N'}"
                               f"-{term // 12}Y-{lo}-{hi}",
                        "name": f"{base['family']}{name_ed}, {lo}-{hi} {base['unit_word']}, {term // 12} "
                                f"{'год' if term == 12 else 'года'}, {'продление' if ptype == 'renewal' else 'новая лицензия'}",
                        "edition": ed_name or base.get("edition", ""),
                        "purchase_type": ptype, "license_type": "subscription", "term_months": term,
                        "users_min": lo, "users_max": hi, "pricing": "per_unit", "price": round(price, 2),
                    })
    return out


def _package_family(base: dict[str, Any], code: str, packages: dict[int, float], renewal_factor: float = 0.55,
                    terms=(12,)) -> list[dict[str, Any]]:
    out = []
    for ptype in ("new", "renewal"):
        for term in terms:
            for users, price in packages.items():
                p = price * (renewal_factor if ptype == "renewal" else 1.0) * (term / 12)
                out.append({
                    **base,
                    "sku": f"{code}-{'R' if ptype == 'renewal' else 'N'}-{term // 12}Y-{users}",
                    "name": f"{base['family']}, до {users} {base['unit_word']}, {term // 12} год, "
                            f"{'продление' if ptype == 'renewal' else 'новая лицензия'}",
                    "purchase_type": ptype, "license_type": "subscription", "term_months": term,
                    "users_min": 0, "users_max": users, "pricing": "package", "price": round(p, 2), "unit": "пакет",
                })
    return out


