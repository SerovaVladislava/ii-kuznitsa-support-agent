def seed_if_empty() -> dict[str, int]:
    created = {"products": 0, "kb": 0, "support_examples": 0}
    if not db.scalar("SELECT COUNT(*) FROM products"):
        created["products"] = catalog.bulk_upsert(demo_products())["created_or_updated"]
    if not db.scalar("SELECT COUNT(*) FROM kb_articles"):
        for q, a, tags, url in KB:
            knowledge.save_article(q, a, tags, source="manual", url=url)
            created["kb"] += 1
    if not support_examples.count():
        for q, a in SUPPORT_EXAMPLES:
            support_examples.add(q, a, source="демо-примеры")
            created["support_examples"] += 1
    return created
